import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

// Execute with the installed Electron binary and ELECTRON_RUN_AS_NODE=1.
assert.equal(process.versions.electron !== undefined, true, "use packaged Electron runtime");
const runtimeRoot = resolve(process.argv[2]);
const resources = resolve(dirname(process.execPath), "../Resources/app");
const fixture = mkdtempSync(join(tmpdir(), "pi-dsh-runtime-"));
const directories = Object.fromEntries(
	["workspace", "data", "agent", "sessions", "home"].map((name) => [name, join(fixture, name)]),
);
for (const path of Object.values(directories)) mkdirSync(path, { recursive: true });
process.env.PATH = "/usr/bin:/bin:/usr/sbin:/sbin";
for (const key of ["DEEPSEEK_API_KEY", "OPENAI_API_KEY", "ANTHROPIC_API_KEY"]) delete process.env[key];
process.env.PI_WEB_DSH_RUNTIME = join(runtimeRoot, "node_modules");
process.env.DSH_HOME = directories.home;
const { DshRuntime } = await import(pathToFileURL(join(resources, "dist/server/dsh/dsh-client.js")).href);
const { generatePresetClones } = await import(pathToFileURL(join(resources, "dist/server/dsh/preset-clones.js")).href);
const clones = generatePresetClones(directories.data);
assert(clones, "official shipped preset clones generated by original adapter");
const runtime = new DshRuntime({
	cwd: directories.workspace,
	dataDir: directories.data,
	agentDir: directories.agent,
	sessionRoot: directories.sessions,
	env: {
		DSH_HOME: directories.home,
		PI_WEB_DSH_RUNTIME: process.env.PI_WEB_DSH_RUNTIME,
		PI_WEB_DSH_PRESET_PATCH: clones.patchFile,
	},
});
const checks = [];
try {
	await runtime.start();
	assert(runtime.alive);
	checks.push({
		status: "PASS",
		check:
			"installed packaged adapter and launcher initialize official external DSH runtime with no system Node or credentials",
	});
	const presets = await runtime.listPresets();
	assert.equal(presets.unavailable, undefined);
	assert(presets.presets.length >= 4);
	assert(presets.presets.every((preset) => !preset.broken));
	checks.push({ status: "PASS", check: "real runtime provides at least four healthy presets", presets });
	const tools = await runtime.listTools();
	assert(tools.tools.length > 0);
	checks.push({ status: "PASS", check: "real runtime tool schema RPC", tools: tools.tools.map((tool) => tool.name) });
	const skills = await runtime.listSkills();
	assert.equal(skills.error, undefined);
	checks.push({ status: "PASS", check: "real runtime skill RPC", count: skills.skills.length });
	const models = await runtime.listModels();
	checks.push({ status: "PASS", check: "real runtime model catalog RPC", models });
} catch (error) {
	checks.push({ status: "FAIL", error: error.stack });
	process.exitCode = 1;
} finally {
	await runtime.close();
	assert(!runtime.alive);
	const result = { fixture, executablePath: process.execPath, runtimeRoot, requestsToModels: 0, checks };
	writeFileSync("docs/desktop-delivery/evidence/T14-dsh-runtime.json", JSON.stringify(result, null, 2));
	console.log(JSON.stringify(checks, null, 2));
}
